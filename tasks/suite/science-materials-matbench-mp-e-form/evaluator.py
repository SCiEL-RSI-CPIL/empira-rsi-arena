"""Matbench v0.1 mp_e_form

Protocol: new_open_problem. Candidate contract: fit_predict(train_inputs, train_targets, test_inputs, info) -> list of len(test_inputs) numbers. Every input is a dict with the keys lattice (the three lattice vectors in angstrom, a 3 x 3 list), species (the element symbol of every site) and frac_coords (the fractional coordinates of every site). info has task, input_type, target, unit, fold, n_train and n_test. Score: mean over the five folds of the held-out mean absolute error, minimized.
Generated by scripts/build_new_tasks.py from the family "matbench" of suite/_lib/arnew. Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from arnew import common  # noqa: E402
from arnew import matbench  # noqa: E402

runtime = common.runtime
DIRECTION = "minimize"
TIMEOUT = 3600
P = {'task': 'mp_e_form', 'classification': False, 'best_known': 0.017, 'wall': 600}


def task(module):
    value, details = matbench.score(module, P["task"], P["wall"])
    best = P["best_known"]
    better = value > best if P["classification"] else value < best
    return runtime.success(value, DIRECTION, benchmark="matbench_" + P["task"], best_known=best, beats_best_known=bool(better), **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
