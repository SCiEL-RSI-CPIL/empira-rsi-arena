from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import sandboxed  # noqa: E402
from autoresearch_suite import agent_bench_core  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 3600
P = {'adapter': 'balrog', 'runtime': 'pinned', 'suite': 'minihack', 'split': 'all', 'episodes_per_task': 1, 'base_seed': 99, 'max_steps': 100, 'budget_usd': 1.0}


