"""Football pool problem for 8 matches: ternary covering code K_3(8,1) (Open combinatorial design, coding and assignment problems with published records supplement).

Protocol: recreated_verified. Candidate contract: construct(q, n, radius) -> list of codewords; the evaluator passes this task's alphabet size q, length n and covering radius. Each codeword is a list of n integers in 0..q-1 and codewords must be distinct. Valid when every word of {0..q-1}^n is within Hamming distance radius of some codeword (checked over the whole space). Score: the number of codewords, minimized; it is an upper bound on K_q(n, radius)..
Generated by scripts/build_suite.py from the family "science_frontier_combinatorics_covering_code" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import frontier_combinatorics_codes  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'q': 3, 'n': 8, 'radius': 1, 'published': 486}


def task(module):
    code = module.construct(P['q'], P['n'], P['radius'])
    value, details = frontier_combinatorics_codes.covering_code(code, P['q'], P['n'], P['radius'])
    return runtime.success(value, 'minimize', best_known=P['published'], beats_best_known=value < P['published'], **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
