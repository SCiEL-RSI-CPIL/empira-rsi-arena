"""TravelPlanner (Mind Evolution).

Protocol: recreated_verified. Candidate contract: solve(question: str, llm) -> str. `question` is a TravelPlanner query, the query's reference information (TravelPlanner's sole-planning input) and the required plan format; `llm(...)` is a budgeted, cached OpenRouter chat client. The JSON list that ends last in the reply must hold one record per day with the keys days, current_city, transportation, breakfast, attraction, lunch, dinner and accommodation. A query is solved when the plan passes all eight commonsense and all five hard constraints of TravelPlanner's evaluation (Final Pass Rate). Score: success rate on a fixed 20-query sample of the 180 validation queries; higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_plan" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_plan  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'benchmark': 'travelplanner', 'samples': 20, 'seed': 0}


def task(module):
    out = llm_bench_plan.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
