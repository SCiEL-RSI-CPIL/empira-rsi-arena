"""Quadratic assignment, QAPLIB tai60b

Protocol: new_open_problem. Candidate contract: solve(a, b) -> permutation p of 0..n-1 (a list of n integers, each exactly once). a and b are the first and second matrix of the QAPLIB file (int64 arrays of shape (n, n), passed as copies). Score: the exact integer cost, the sum over all i and j of a[i, j] * b[p[i], p[j]], minimized.
Generated by scripts/build_new_tasks.py from the family "qap" of suite/_lib/arnew. Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from arnew import common  # noqa: E402
from arnew import qap  # noqa: E402

runtime = common.runtime
DIRECTION = "minimize"
TIMEOUT = 120
P = {'instance': 'tai60b', 'n': 60, 'lower_bound': 592371800, 'best_known': 608215054}


def task(module):
    a, b = qap.instance(P["instance"])
    permutation = module.solve(a.copy(), b.copy())
    value, details = qap.objective(permutation, a, b)
    return runtime.success(value, "minimize", instance=P["instance"], best_known=P["best_known"],
                           beats_best_known=value < P["best_known"], **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
