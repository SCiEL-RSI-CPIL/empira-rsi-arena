"""IMO-ProofBench (Meta-Harness).

Protocol: recreated. Candidate contract: solve(question: str, llm) -> str: a complete proof for an IMO-ProofBench problem (`question` is the problem statement and a request for a rigorous proof). `llm(...)` is a budgeted, cached OpenRouter chat client. A judge model grades the proof against the reference solution and the problem's grading guidelines on IMO-Bench's 0/1/6/7-point scale (first <points>N out of 7</points> block of its reply; unparsable grades count as 0). Score: mean points / 7 over a fixed seeded sample of the 60 problems; higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_proof" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_proof  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 1800
P = {'samples': 20, 'seed': 0, 'judge_model': 'google/gemini-2.5-flash', 'judge_max_tokens': 8192, 'budget_usd': 1.0}


def task(module):
    out = llm_bench_proof.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
