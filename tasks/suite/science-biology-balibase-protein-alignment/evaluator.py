"""Biology: protein multiple-alignment accuracy on BAliBASE reference alignments (Biology research supplement).

Protocol: recreated_verified. Candidate contract: align(sequences) -> list of aligned rows, one per input sequence, all of the same length, each row equal to its input sequence with '-' gap characters inserted (upper-case amino acids). sequences is a list of 4 to 10 unaligned protein sequences of a BAliBASE reference-1 test case. align is called once per test case in a sandboxed subprocess with a 240 s CPU budget for all 26 cases. Score (maximize): mean sum-of-pairs score over the cases, i.e. the fraction of residue pairs that the structure-based reference alignment places in the same core-block column and the candidate also aligns; the total-column score is reported alongside.
Generated by scripts/build_suite.py from the family "biology_research_balibase_alignment" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import bio_align  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 300
P = {'cpu_seconds': 240}


def task(module):
    value, details = bio_align.score(module, P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
