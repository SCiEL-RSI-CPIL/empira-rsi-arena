from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import frontier_combinatorics_qap  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'instance': 'wil100', 'n': 100, 'sha256': '9477abe6459def2fc664ee49f612a592bba7b59c2a3027c4a0382d068c6aa4ca', 'published': 273038}


def task(module):
    a, b = frontier_combinatorics_qap.instance(P['instance'], P['sha256'])
    permutation = module.solve(a.copy(), b.copy())
    value, details = frontier_combinatorics_qap.objective(permutation, a, b)
    return runtime.success(value, 'minimize', instance=P['instance'], best_known=P['published'], beats_best_known=value < P['published'], **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
