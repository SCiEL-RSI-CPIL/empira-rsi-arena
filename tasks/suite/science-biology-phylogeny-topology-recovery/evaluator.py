"""Biology: phylogenetic topology recovery from simulated sequences (Biology research supplement).

Protocol: recreated_verified. Candidate contract: reconstruct(sequences) -> Newick string over the labels t0..t(n-1) (branch lengths optional, trailing semicolon optional, every taxon exactly once). sequences maps those labels to equal-length DNA strings over ACGT simulated along an unknown tree. reconstruct is called once per instance in a sandboxed subprocess with a 180 s CPU budget for all 20 instances (8 to 32 taxa, 250 to 2000 sites). Score (minimize): mean normalized Robinson-Foulds distance between the non-trivial unrooted splits of the returned tree and those of the generating tree; 0 means recovering every topology exactly.
Generated by scripts/build_suite.py from the family "biology_research_phylogeny_topology" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import bio_phylo  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 240
P = {'cpu_seconds': 180}


def task(module):
    value, details = bio_phylo.score(module, P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
