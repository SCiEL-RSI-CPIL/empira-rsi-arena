"""Natural Plan Meeting Planning (Mind Evolution).

Protocol: recreated_verified. Candidate contract: solve(question: str, llm) -> str. `question` is Natural Plan's 5-shot Meeting Planning prompt (meet as many friends as possible in San Francisco under availability, location and travel-time constraints; answer starting with 'SOLUTION:' in the shown step format). `llm(...)` is a budgeted, cached OpenRouter chat client. Plan checker (port of Natural Plan's evaluate_meeting_planning.py): the text after 'SOLUTION:' is split on periods and simulated step by step ('You start/travel/wait/meet ...'); the count of valid meetings before the first invalid step must equal that of the golden plan. Score: success rate on a fixed 30-problem sample of Mind Evolution's 500-problem test split; higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_plan" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_plan  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'benchmark': 'meeting_planning', 'samples': 30, 'seed': 0}


def task(module):
    out = llm_bench_plan.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
