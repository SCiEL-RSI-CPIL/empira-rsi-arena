from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import bio_flu  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 240
P = {'season': '2024-2025', 'cpu_seconds': 180}


def task(module):
    value, details = bio_flu.score(module, P)
    return runtime.success(value, 'minimize', **details)


