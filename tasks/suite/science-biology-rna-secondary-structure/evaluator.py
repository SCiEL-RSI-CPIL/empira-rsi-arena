"""Biology: RNA secondary-structure prediction against Rfam consensus structures (Biology research supplement).

Protocol: recreated_verified. Candidate contract: predict_structure(sequence) -> dot-bracket string of the same length as sequence, containing only '.', '(' and ')' with balanced brackets. sequence is an ACGU string of 40 to 150 nucleotides from an Rfam family that has a three-dimensional structure. predict_structure is called once per sequence in a sandboxed subprocess with a 180 s CPU budget for all 90 sequences. Score (maximize): mean F1 of the predicted base-pair set against the reference pairs, i.e. the harmonic mean of sensitivity and precision; sensitivity and precision are reported separately.
Generated by scripts/build_suite.py from the family "biology_research_rna_structure" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import bio_rna  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 240
P = {'cpu_seconds': 180}


def task(module):
    value, details = bio_rna.score(module, P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
