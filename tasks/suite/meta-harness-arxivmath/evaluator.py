"""ArXivMath (Meta-Harness).

Protocol: recreated. Candidate contract: solve(question: str, llm) -> str. `llm(prompt_or_messages, system=None, max_tokens=None, temperature=None, json_mode=False) -> str` is a budgeted, cached OpenRouter chat client. `question` is an ArXivMath problem followed by 'Put your final answer within \boxed{}.' Answer rule: the content of the reply's last \boxed{...} (else the final answer text after the last 'Answer:' marker or the last line) is parsed as LaTeX and must be equivalent to the gold answer under Math-Verify 0.9.0 (symbolic and numeric equivalence; ordered tuples must match in order). Score: accuracy over all 40 ArXivMath December 2025 and January 2026 problems; higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_qa" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_qa  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'benchmark': 'arxivmath', 'samples': 40, 'seed': 0, 'budget_usd': 0.6}


def task(module):
    out = llm_bench_qa.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
