"""IMO-GradingBench (HyperAgents).

Protocol: recreated. Candidate contract: solve(question: str, llm) -> str. `llm(prompt_or_messages, system=None, max_tokens=None, temperature=None, json_mode=False) -> str` is a budgeted, cached OpenRouter chat client. `question` gives an IMO-level problem, its reference solution, the grading guidelines and a proposed proof, and asks for one grade among correct, almost, partial and incorrect. Answer rule (this suite's answer extraction; the comparison follows Hyperagents' report.py): the final answer (the text after the last 'Answer:' marker, else the last \boxed{...}, else the last non-empty line), lower-cased and stripped of punctuation and asterisks, must equal the human grade. Score: accuracy on a fixed 30-item sample of Hyperagents' 100-item held-out IMO-GradingBench subset (normalized mean absolute error is reported alongside); higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_qa" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_qa  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'benchmark': 'gradingbench', 'samples': 30, 'seed': 0}


def task(module):
    out = llm_bench_qa.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
