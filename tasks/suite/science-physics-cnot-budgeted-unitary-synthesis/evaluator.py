"""Physics: exact quantum circuit synthesis within published CNOT budgets (Physics research supplement).

Protocol: recreated_verified. Candidate contract: synthesize(problem) -> list of gates. problem has keys name, qubits (2 or 3), cnot_budget and the target unitary as real and imaginary (nested lists of 2**qubits rows). A gate is ['u3', qubit, theta, phi, lam] for the standard single-qubit rotation or ['cx', control, target] for a CNOT; qubit 0 is the most significant bit of the basis index. At most cnot_budget CNOTs and 400 gates per circuit. synthesize is called once per target in a sandboxed subprocess with a 150 s CPU budget for all seven targets. Score (minimize): mean over the targets of the phase-insensitive distance 1 - |tr(target^dagger U)| / 2**qubits, where the evaluator rebuilds U from the gate list; 0 means exact synthesis of every target within its budget.
Generated by scripts/build_suite.py from the family "physics_research_unitary_synthesis" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import sandboxed  # noqa: E402
from autoresearch_suite import phys_quantum  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 240
P = {'cpu_seconds': 150}


def task(module):
    value, details = phys_quantum.synthesis_score(module, P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = sandboxed.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
