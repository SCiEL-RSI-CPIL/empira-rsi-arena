"""Single-step code bug repair (ELM).

Protocol: recreated. Candidate contract: solve(question: str, llm) -> str. `question` shows one of ELM's seven buggy programs in ELM's prompt layout ('# A buggy implementation', the code, '# Fixed Bugs'), an attempt number and a request for the complete fixed implementation; `llm(...)` is a budgeted, cached OpenRouter chat client. The last ```python block of the reply (else the whole reply) is executed in a resource-limited child process: the repaired 4-Parity function must return the parity of all 16 inputs and the repaired Quadratic function must return a*x^2+b*x+c on 320 grid points. Score: the fraction of the 28 (program, attempt) pairs repaired in one step, an estimate of the single-step repair success probability; higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_code" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_code  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 1800
P = {'benchmark': 'elm_repair', 'trials': 4, 'samples': 28, 'seed': 0}


def task(module):
    out = llm_bench_code.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
