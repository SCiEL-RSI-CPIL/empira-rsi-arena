from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import sandboxed  # noqa: E402
from autoresearch_suite import agent_bench_core  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 3600
P = {'adapter': 'alfworld', 'runtime': 'pinned', 'per_type': 2, 'seed': 0, 'max_steps': 49, 'budget_usd': 0.5}


def task(module):
    out = agent_bench_core.evaluate_task(module, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = sandboxed.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
