"""CPU MuJoCo analogues of two IsaacGymEnvs tasks used by Eureka (BallBalance, Quadcopter).

Both follow the task files pinned in the Eureka repository
(eureka-research/Eureka@9eee42808b52d8abc14845d1547bfde886403ccc,
isaacgymenvs/isaacgymenvs/tasks/ball_balance.py and quadcopter.py, BSD-3-Clause
NVIDIA headers): same geometry and masses, control period (dt 0.01 s), action
integration, reset distributions, termination rules and task fitness. No Isaac
Gym code is copied; the models are rebuilt as MJCF for MuJoCo.

Deviations (also stated in the task notes):

* BallBalance: Isaac's tray rests on three two-link legs whose feet are held by
  PhysX rigid-body attractors; a direct MuJoCo translation was unstable. Here
  the same tray (radius 0.5 m, 0.02 m thick, density 100) sits at the same
  height on a fixed-base two-axis gimbal whose tilt joints are position-driven
  (targets += dt * 20 * action, as Isaac's leg targets). Actions are 2 tilt
  rates instead of 3 leg rates and the observation is 10-dimensional
  (tilts, tilt rates, ball position and velocity) instead of 24 (leg joints and
  force-sensor readings).
* Quadcopter: the MJCF generated by _create_quadcopter_asset is reproduced; the
  rotor pitch/roll joints are driven by position actuators (Isaac stiffness
  1000, damping 0) with added armature and damping because MuJoCo's explicit
  actuator integration is unstable for the tiny rotor inertia. Isaac's
  per-body angular velocity cap (4 pi rad/s) is applied to the chassis only.

A step on which MuJoCo reports a numerical instability (it would silently reset
the state) ends the episode as a failure and returns the last finite state, so
an unstable policy can never be teleported back to its initial state.
"""
from __future__ import annotations

import math

import numpy as np

from . import sim_control_eureka_views as views

DT = 0.01


def _mujoco():
    try:
        import mujoco
    except ImportError as error:  # pragma: no cover - environment problem
        raise RuntimeError(f"mujoco is required: {error}") from None
    return mujoco


class _Guard:
    """Detects MuJoCo's bad-acceleration warning (after which MuJoCo resets the state)."""

    def __init__(self, mujoco, data):
        self.index = int(mujoco.mjtWarning.mjWARN_BADQACC)
        self.data = data
        self.seen = 0
        self.events = 0

    def sync(self):
        self.seen = int(self.data.warning[self.index].number)

    def tripped(self, state):
        count = int(self.data.warning[self.index].number)
        bad = count > self.seen or not np.all(np.isfinite(state))
        self.seen = count
        self.events += int(bad)
        return bad


def _rotate(quat_wxyz, vector):
    w, x, y, z = quat_wxyz
    matrix = np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                       [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                       [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])
    return matrix @ np.asarray(vector, dtype=float)


# ---------------------------------------------------------------------------
# BallBalance analogue: fixed-base gimbal tray
# ---------------------------------------------------------------------------

TRAY_RADIUS, TRAY_THICKNESS = 0.5, 0.02
LEG_RADIUS = 0.02
LEG_LENGTH = TRAY_RADIUS - 0.1 - 2 * LEG_RADIUS
TRAY_HEIGHT = LEG_LENGTH * math.sqrt(2) + 2 * LEG_RADIUS + 0.5 * TRAY_THICKNESS  # 0.5591 m, as in Isaac
BALL_RADIUS = 0.1
MAX_TILT = math.radians(30.0)
TRAY_SPEED_SCALE = 20.0  # actionSpeedScale in BallBalance.yaml
TRAY_EPISODE = 500  # maxEpisodeLength

TRAY_XML = f"""<mujoco model="GimbalTray">
  <compiler angle="radian" inertiafromgeom="true"/>
  <option timestep="0.002" gravity="0 0 -9.81"/>
  <worldbody>
    <geom name="floor" type="plane" size="10 10 0.1" contype="0" conaffinity="1"/>
    <body name="gimbal" pos="0 0 {TRAY_HEIGHT:.6f}">
      <joint name="tilt_x" type="hinge" axis="1 0 0" limited="true" range="{-MAX_TILT:.6f} {MAX_TILT:.6f}" armature="0.05" damping="2"/>
      <geom type="sphere" size="0.01" density="100" contype="0" conaffinity="0"/>
      <body name="tray">
        <joint name="tilt_y" type="hinge" axis="0 1 0" limited="true" range="{-MAX_TILT:.6f} {MAX_TILT:.6f}" armature="0.05" damping="2"/>
        <geom name="tray" type="cylinder" size="{TRAY_RADIUS} {0.5 * TRAY_THICKNESS}" density="100" contype="1" conaffinity="1"/>
      </body>
    </body>
    <body name="ball" pos="0.2 0 2">
      <freejoint name="ball"/>
      <geom name="ball" type="sphere" size="{BALL_RADIUS}" density="200" contype="1" conaffinity="1"/>
    </body>
  </worldbody>
  <actuator>
    <position joint="tilt_x" kp="400" kv="20" ctrlrange="{-MAX_TILT:.6f} {MAX_TILT:.6f}" ctrllimited="true"/>
    <position joint="tilt_y" kp="400" kv="20" ctrlrange="{-MAX_TILT:.6f} {MAX_TILT:.6f}" ctrllimited="true"/>
  </actuator>
</mujoco>"""


class TrayEnv:
    """BallBalance analogue. Observation (10): tilt_x, tilt_y, their rates, ball position (3), ball velocity (3)."""

    name = "ballbalance"
    obs_dim, act_dim, state_dim, horizon = 10, 2, 13, TRAY_EPISODE

    def __init__(self):
        mujoco = _mujoco()
        self._mj = mujoco
        self.model = mujoco.MjModel.from_xml_string(TRAY_XML)
        self.data = mujoco.MjData(self.model)
        self.tray_body = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_BODY, "tray")
        self.guard = _Guard(mujoco, self.data)
        self.targets = np.zeros(2)
        self.progress = 0
        self.last = None

    def reset(self, rng):
        """Ball thrown as in IsaacGymEnvs BallBalance.reset_idx; tray level, targets zero."""
        self._mj.mj_resetData(self.model, self.data)
        dist = rng.uniform(0.001, 0.5)
        angle = rng.uniform(0.0, 2.0 * math.pi)
        direction = np.array([math.cos(angle), math.sin(angle)])
        speed = (dist - 0.001) / (0.5 - 0.001) * rng.uniform(0.0, 5.0)
        height = rng.uniform(1.0, 2.0)
        self.data.qpos[2:5] = [dist * direction[0], dist * direction[1], height]
        self.data.qpos[5:9] = [1.0, 0.0, 0.0, 0.0]
        self.data.qvel[2:5] = [-speed * direction[0], -speed * direction[1], -5.0]
        self._mj.mj_forward(self.model, self.data)
        self.targets[:] = 0.0
        self.progress = 0
        self.guard.sync()
        self.last = self.state()
        return self.last

    def state(self):
        """Raw state: tilts (2), tilt rates (2), ball position (3), ball velocity (3), tray normal (3)."""
        normal = self.data.xmat[self.tray_body].reshape(3, 3)[:, 2]
        return np.concatenate([self.data.qpos[0:2], self.data.qvel[0:2], self.data.qpos[2:5], self.data.qvel[2:5], normal])

    observe = staticmethod(views.observe_ballbalance)
    info = staticmethod(views.info_ballbalance)

    def step(self, action):
        action = np.clip(np.asarray(action, dtype=float), -1.0, 1.0)
        self.targets = np.clip(self.targets + DT * TRAY_SPEED_SCALE * action, -MAX_TILT, MAX_TILT)
        self.data.ctrl[:] = self.targets
        for _ in range(5):
            self._mj.mj_step(self.model, self.data)
        self.progress += 1
        state = self.state()
        if self.guard.tripped(state):
            return self.last, True, True
        self.last = state
        dropped = bool(state[6] < 1.5 * BALL_RADIUS)
        return state, dropped, dropped or self.progress >= TRAY_EPISODE

    @staticmethod
    def human_reward(state):
        """Eureka/IsaacGymEnvs compute_bbot_reward (pos_reward * speed_reward), on the analogue's state."""
        ball, velocity = state[4:7], state[7:10]
        ball_dist = math.sqrt(ball[0] ** 2 + (ball[2] - 0.7) ** 2 + ball[1] ** 2)
        speed = math.sqrt(float(velocity @ velocity))
        return 1.0 / (1.0 + ball_dist) * (1.0 / (1.0 + speed))


# ---------------------------------------------------------------------------
# Quadcopter port
# ---------------------------------------------------------------------------

QUAD_TARGET = np.array([0.0, 0.0, 1.0])
QUAD_EPISODE = 500
ROTOR_LIMIT = math.radians(30.0)
MAX_THRUST = 2.0
DOF_SPEED_SCALE = 8.0 * math.pi
THRUST_SPEED_SCALE = 200.0
MAX_ANGULAR_VELOCITY = 4.0 * math.pi


def _quad_xml():
    chassis_radius, chassis_thickness = 0.1, 0.03
    rotor_radius, rotor_thickness, arm_radius = 0.04, 0.01, 0.01
    parts = ['<mujoco model="Quadcopter"><compiler angle="radian" inertiafromgeom="true"/>',
             '<option timestep="0.005" gravity="0 0 -9.81"/><worldbody>',
             '<geom name="floor" type="plane" size="20 20 0.1" contype="0" conaffinity="1"/>',
             '<body name="chassis" pos="0 0 1"><freejoint name="root_joint"/>',
             f'<geom type="cylinder" size="{chassis_radius} {0.5 * chassis_thickness}" density="50" contype="1" conaffinity="0"/>']
    for i, angle in enumerate([0.25 * math.pi, 0.75 * math.pi, 1.25 * math.pi, 1.75 * math.pi]):
        quat = [math.cos(angle / 2), 0.0, 0.0, math.sin(angle / 2)]
        pos = _rotate(quat, (chassis_radius + 0.25 * arm_radius, 0.0, 0.0))
        parts += [f'<body name="rotor_arm{i}" pos="{pos[0]:.9f} {pos[1]:.9f} {pos[2]:.9f}" quat="{quat[0]:.9f} 0 0 {quat[3]:.9f}">',
                  f'<geom type="sphere" size="{arm_radius}" density="200" contype="1" conaffinity="0"/>',
                  f'<joint name="rotor_pitch{i}" type="hinge" axis="0 1 0" limited="true" range="{-ROTOR_LIMIT:.9f} {ROTOR_LIMIT:.9f}" armature="0.01" damping="1"/>',
                  f'<body name="rotor{i}" pos="{rotor_radius + 0.25 * arm_radius} 0 0">',
                  f'<geom type="cylinder" size="{rotor_radius} {0.5 * rotor_thickness}" density="1000" contype="1" conaffinity="0"/>',
                  f'<joint name="rotor_roll{i}" type="hinge" axis="1 0 0" limited="true" range="{-ROTOR_LIMIT:.9f} {ROTOR_LIMIT:.9f}" armature="0.01" damping="1"/>',
                  '</body></body>']
    parts.append('</body></worldbody><actuator>')
    for i in range(4):
        for joint in (f"rotor_pitch{i}", f"rotor_roll{i}"):
            parts.append(f'<position joint="{joint}" kp="1000" ctrlrange="{-ROTOR_LIMIT:.9f} {ROTOR_LIMIT:.9f}" ctrllimited="true"/>')
    parts.append('</actuator></mujoco>')
    return "".join(parts)


class QuadEnv:
    """Quadcopter port. Observation (21) as Isaac's compute_observations; actions: 8 rotor-joint rates, 4 thrust rates."""

    name = "quadcopter"
    obs_dim, act_dim, state_dim, horizon = 21, 12, 25, QUAD_EPISODE

    def __init__(self):
        mujoco = _mujoco()
        self._mj = mujoco
        self.model = mujoco.MjModel.from_xml_string(_quad_xml())
        self.data = mujoco.MjData(self.model)
        self.rotors = [mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_BODY, f"rotor{i}") for i in range(4)]
        joints = [f"rotor_{kind}{i}" for i in range(4) for kind in ("pitch", "roll")]
        self.dof_qpos = np.array([self.model.jnt_qposadr[mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_JOINT, j)] for j in joints])
        self.guard = _Guard(mujoco, self.data)
        self.last = None
        self.targets = np.zeros(8)
        self.thrusts = np.zeros(4)
        self.progress = 0
        self.fresh = True

    def reset(self, rng):
        """IsaacGymEnvs Quadcopter.reset_idx: position offsets, rotor joints U(-0.2, 0.2), thrusts and targets reset."""
        self._mj.mj_resetData(self.model, self.data)
        self.data.qpos[0] = rng.uniform(-1.5, 1.5)
        self.data.qpos[1] = rng.uniform(-1.5, 1.5)
        self.data.qpos[2] = 1.0 + rng.uniform(-0.2, 1.5)
        self.data.qpos[3:7] = [1.0, 0.0, 0.0, 0.0]
        self.data.qpos[self.dof_qpos] = rng.uniform(-0.2, 0.2, 8)
        self._mj.mj_forward(self.model, self.data)
        self.targets = self.data.qpos[self.dof_qpos].copy()
        self.thrusts = np.zeros(4)
        self.progress = 0
        self.fresh = True  # Isaac ignores the action of the step that follows a reset
        self.guard.sync()
        self.last = self.state()
        return self.last

    def state(self):
        """Raw state: position (3), quaternion wxyz (4), linear velocity (3), world angular velocity (3), rotor joints (8), thrusts (4)."""
        quat = self.data.qpos[3:7].copy()
        angvel = _rotate(quat, self.data.qvel[3:6])
        return np.concatenate([self.data.qpos[0:3], quat, self.data.qvel[0:3], angvel, self.data.qpos[self.dof_qpos], self.thrusts])

    observe = staticmethod(views.observe_quadcopter)
    info = staticmethod(views.info_quadcopter)

    def step(self, action):
        action = np.clip(np.asarray(action, dtype=float), -1.0, 1.0)
        if self.fresh:
            self.fresh = False
        else:
            self.targets = np.clip(self.targets + DT * DOF_SPEED_SCALE * action[0:8], -ROTOR_LIMIT, ROTOR_LIMIT)
            self.thrusts = np.clip(self.thrusts + DT * THRUST_SPEED_SCALE * action[8:12], 0.0, MAX_THRUST)
        self.data.ctrl[:] = self.targets
        for _ in range(2):  # Quadcopter.yaml: dt 0.01 with 2 substeps; thrust along each rotor's local z axis
            self.data.xfrc_applied[:] = 0.0
            for k, body in enumerate(self.rotors):
                self.data.xfrc_applied[body, 0:3] = self.thrusts[k] * self.data.xmat[body].reshape(3, 3)[:, 2]
            self._mj.mj_step(self.model, self.data)
            spin = float(np.linalg.norm(self.data.qvel[3:6]))
            if spin > MAX_ANGULAR_VELOCITY:  # Isaac asset option max_angular_velocity = 4 pi
                self.data.qvel[3:6] *= MAX_ANGULAR_VELOCITY / spin
        self.progress += 1
        state = self.state()
        if self.guard.tripped(state):
            return self.last, True, True
        self.last = state
        distance = float(np.linalg.norm(state[0:3] - QUAD_TARGET))
        died = distance > 3.0 or state[2] < 0.3
        return state, died, died or self.progress >= QUAD_EPISODE

    @staticmethod
    def human_reward(state):
        """Eureka/IsaacGymEnvs compute_quadcopter_reward on the port's state."""
        position, quat, angvel = state[0:3], state[3:7], state[10:13]
        distance = float(np.linalg.norm(position - QUAD_TARGET))
        pos_reward = 1.0 / (1.0 + distance * distance)
        tilt = abs(1.0 - _rotate(quat, (0.0, 0.0, 1.0))[2])
        up_reward = 1.0 / (1.0 + tilt * tilt)
        spin = abs(angvel[2])
        spin_reward = 1.0 / (1.0 + spin * spin)
        return pos_reward + pos_reward * (up_reward + spin_reward)


ENVS = {"ballbalance": TrayEnv, "quadcopter": QuadEnv}
