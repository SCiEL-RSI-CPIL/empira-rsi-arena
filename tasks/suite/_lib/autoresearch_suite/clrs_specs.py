def task_algorithm(task_id):
    """``evoprompting-<name>`` task id -> CLRS algorithm name."""
    slug = task_id.removeprefix("evoprompting-")
    name = "kmp_matcher" if slug == "knuth-morris-pratt" else slug.replace("-", "_")
    if name not in SPECS:
        raise KeyError(f"{task_id} is not a CLRS-30 task")
    return name


