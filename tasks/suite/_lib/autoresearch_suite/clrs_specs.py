def model_spec(algorithm):
    """The spec the model sees: pred_h moved to inputs, sorting outputs as permutation + first-node mask."""
    spec = {}
    for name, (stage, loc, typ) in SPECS[algorithm].items():
        if name == "pred_h" and algorithm in PRED_AS_INPUT:
            assert (stage, loc, typ) == (HINT, NODE, POINTER)
            spec["pred"] = (INPUT, NODE, POINTER)
        elif typ == SHOULD_BE_PERMUTATION:
            spec[name] = (stage, loc, PERMUTATION_POINTER)
            spec[name + "_mask"] = (stage, loc, MASK_ONE)
        else:
            spec[name] = (stage, loc, typ)
    return spec
