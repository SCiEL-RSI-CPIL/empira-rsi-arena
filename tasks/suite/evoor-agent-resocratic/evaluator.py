"""ReSocratic (EvoOR-Agent).

Protocol: recreated. Candidate contract: solve(question: str, llm) -> str. `llm(prompt_or_messages, system=None, max_tokens=None, temperature=None, json_mode=False) -> str` is a budgeted, cached OpenRouter chat client; the program may also run code locally (numpy and scipy, including scipy.optimize.milp and linprog, are available). `question` is an OptiBench/ReSocratic optimization problem followed by the JSON list of quantity names to report. Answer rule: the reply must contain a JSON object (read from the final answer (the text after the last 'Answer:' marker, else the last \boxed{...}, else the last non-empty line), else the JSON object that ends last in the reply) mapping every requested name (case and whitespace insensitive) to a number; the problem scores 1 only if every value satisfies |value - gold| <= max(1e-4, 1e-3 * |gold|). Score: accuracy on a fixed 30-problem sample of the 403 cleaned problems; higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_qa" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_qa  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'benchmark': 'resocratic', 'samples': 30, 'seed': 0}


def task(module):
    out = llm_bench_qa.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
