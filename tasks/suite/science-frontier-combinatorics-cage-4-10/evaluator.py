from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import frontier_combinatorics_graphs  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'k': 4, 'g': 10, 'max_vertices': 50000, 'published': 320}


