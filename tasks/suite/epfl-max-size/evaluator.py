"""EPFL max, LUT-6 count

Protocol: new_open_problem. Candidate contract: script() -> string of ABC commands separated by `;` or newlines. The evaluator runs `read <circuit>; <script>` in ABC and writes out the network the script leaves. That network must consist only of LUTs with at most 6 inputs (in ABC a LUT mapper such as `if -K 6` produces one; library gates or a wider node are invalid), and it must be equivalent to the original circuit, which a separate ABC process checks with `cec`. The script may not contain the characters ! / \\ ~, may not use commands that read or write files, change the session or start other programs (read*, write*, load*, dump*, save* and their short forms, source, alias, set, unset, history, cd, ls, pwd, quit, exit), and may not ask for LUTs wider than 6 inputs (-K above 6). Time limits: 1200 s for the script, 900 s for the equivalence check. A script that is refused, fails, runs out of time or changes the function is invalid. Score: the number of LUTs with two or more inputs (buffers, inverters and constants are not counted), minimized.
Generated by scripts/build_new_tasks.py from the family "epfl" of suite/_lib/arnew. Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from arnew import common  # noqa: E402
from arnew import epfl  # noqa: E402

runtime = common.runtime
DIRECTION = "minimize"
TIMEOUT = 2400
P = {'circuit': 'max', 'folder': 'arithmetic', 'metric': 'size', 'best_known': 511}


def task(module):
    value, details = epfl.evaluate(module.script(), P["circuit"], P["metric"])
    return runtime.success(value, "minimize", circuit=P["circuit"], best_known=P["best_known"],
                           beats_best_known=value < P["best_known"], **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
