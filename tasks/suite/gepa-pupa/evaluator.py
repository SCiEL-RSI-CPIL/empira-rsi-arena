"""PUPA (GEPA, Pairwise Validator).

Protocol: recreated. Candidate contract: solve(user_query: str, llm, untrusted_llm) -> str: the response to a private user request. `llm` is the trusted model (default qwen/qwen3-8b) and `untrusted_llm` an external model (default openai/gpt-4.1-mini); both are budgeted, cached OpenRouter clients and every prompt sent to `untrusted_llm` is recorded. A judge model (default openai/gpt-4.1-mini, as in GEPA) rates quality (is the response at least as good as the target response, asked in both orders) and PII leakage (share of the item's PII units found in what reached `untrusted_llm`). Item score: (quality + (1 - leakage)) / 2. Score: mean over a fixed seeded sample of GEPA's PUPA test split; higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_pupa" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_pupa  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 1800
P = {'samples': 20, 'seed': 0, 'model': 'qwen/qwen3-8b', 'untrusted_model': 'openai/gpt-4.1-mini', 'judge_model': 'openai/gpt-4.1-mini'}


def task(module):
    out = llm_bench_pupa.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
