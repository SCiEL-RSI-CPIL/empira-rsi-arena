"""IFBench (GEPA, Pairwise Validator).

Protocol: recreated. Candidate contract: solve(question: str, llm) -> str. `question` is an IFBench prompt (a user request with one or more verifiable output constraints); the returned text is the response that the IFBench instruction checkers verify. `llm(prompt_or_messages, system=None, max_tokens=None, temperature=None, json_mode=False) -> str` is a budgeted, cached OpenRouter chat client. Score: mean over a fixed seeded sample of prompts of the fraction of instructions followed under GEPA's loose rule (the response, or the response without its first and/or last line and/or without asterisks, passes the checker); higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_ifbench" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_ifbench  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'samples': 30, 'seed': 0}


def task(module):
    out = llm_bench_ifbench.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', valid=None, **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
