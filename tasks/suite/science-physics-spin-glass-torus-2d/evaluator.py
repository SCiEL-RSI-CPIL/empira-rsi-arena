"""Physics: two-dimensional spin-glass ground states on fixed instances (Physics research supplement).

Protocol: recreated_verified. Candidate contract: ground_state(instance) -> list of instance['nodes'] spins, each -1 or +1. instance has keys name, nodes, side, dimension and edges (list of [i, j, weight] with integer weights and 0-based node indices) of a 2-dimensional periodic grid of side 10, 15 and 20 with Gaussian couplings. ground_state is called once per instance in a sandboxed subprocess with a 180 s CPU budget for all nine instances together. Score (maximize): mean over the instances of cut_weight / published_optimal_cut, where the evaluator recomputes the cut weight from the edge list; 1.0 means reaching the exact optimum everywhere. The spin-glass energy of the couplings J = -weight is sum(weight) - 2 * cut_weight, so a larger cut is a lower energy.
Generated by scripts/build_suite.py from the family "physics_research_spin_glass_torus_2d" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import phys_spinglass  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 240
P = {'dimension': 2, 'cpu_seconds': 180}


def task(module):
    value, details = phys_spinglass.score(module, P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
