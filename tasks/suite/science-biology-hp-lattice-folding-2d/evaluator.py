"""Biology: HP lattice protein folding on the square lattice (Biology research supplement).

Protocol: recreated_verified. Candidate contract: fold(sequence, dimension) -> list of len(sequence) integer lattice points (lists of length dimension). sequence is a string of H and P residues; dimension is 2 (square lattice). The returned walk must be self-avoiding with unit steps between consecutive residues. Energy = minus the number of H-H pairs on neighbouring lattice sites that are not adjacent along the chain; the evaluator recomputes it. fold is called once per benchmark sequence in a sandboxed subprocess with a 120 s CPU budget for all sequences together. Score (maximize): mean over the 10 benchmark sequences of energy / best_known_energy (both energies are negative), so 0 is an unfolded chain, 1.0 reproduces every best-known energy and a value above 1.0 beats one.
Generated by scripts/build_suite.py from the family "biology_research_hp_square_lattice" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import bio_hp  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 180
P = {'dimension': 2, 'cpu_seconds': 120}


def task(module):
    value, details = bio_hp.score(module, P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
