"""Gore Vidal sentence sentiment (LMX).

Protocol: recreated_verified. Candidate contract: solve(question: str, llm) -> list[str]: an archive of 1 to 300 one-line sentences of 5 to 400 characters, each valid Unicode text (no unpaired surrogates) and at most 512 tokens for the sentiment classifier's tokenizer (400 characters of CJK text or of some emoji are more). `question` is the target quote; `llm(...)` is an optional budgeted OpenRouter client (it needs OPENROUTER_API_KEY only when called). Each sentence's fitness is the 'positive' probability of cardiffnlp/twitter-roberta-base-sentiment-latest and its niche is the Euclidean distance between its all-MiniLM-L6-v2 embedding and the quote's, clipped to [0, 1.25] and cut into 30 equal bins. Score: QD score, the sum over occupied niches of the best fitness (at most 30); higher is better.
Generated by scripts/build_suite.py from the family "llm_bench_lmx" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm_bench_lmx  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 600
P = {'quote': 'Whenever a friend succeeds, a little something in me dies.', 'niches': 30, 'max_distance': 1.25, 'max_sentences': 300}


def task(module):
    out = llm_bench_lmx.evaluate(module.solve, P)
    return runtime.success(out['score'], 'maximize', **out['details'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
