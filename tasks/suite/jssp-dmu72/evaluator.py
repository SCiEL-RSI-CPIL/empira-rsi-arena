"""Job-shop scheduling dmu72

Protocol: new_open_problem. Candidate contract: solve(inst) -> starts, a list of n_jobs lists of non-negative integers: starts[j][k] is the start time of operation k of job j. inst has name, n_jobs, n_machines and jobs[j] = list of (machine, duration) pairs in processing order, machines numbered from 0. Operation k + 1 of a job may not start before operation k has ended, and two operations on one machine may not overlap (one may start at the moment the other ends). Score: the makespan, minimized.
Generated by scripts/build_new_tasks.py from the family "jssp" of suite/_lib/arnew. Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from arnew import common  # noqa: E402
from arnew import jssp  # noqa: E402

runtime = common.runtime
DIRECTION = "minimize"
TIMEOUT = 300
P = {'instance': 'dmu72', 'lower_bound': 6434, 'best_known': 6448}


def task(module):
    inst = jssp.instance(P["instance"])
    starts = module.solve({"name": inst["name"], "n_jobs": inst["n_jobs"], "n_machines": inst["n_machines"],
                           "jobs": [list(j) for j in inst["jobs"]]})
    value, details = jssp.makespan(starts, inst)
    return runtime.success(value, "minimize", instance=P["instance"], best_known=P["best_known"],
                           beats_best_known=value < P["best_known"], **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
