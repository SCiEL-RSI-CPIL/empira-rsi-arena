"""Max-cut, G-set G13

Protocol: new_open_problem. Candidate contract: solve(n, edges) -> sequence of n integers, each 0 or 1: the side of every vertex. edges is an int64 array with one row (i, j, w) per edge, vertices numbered from 0. Score: total weight of the edges whose endpoints are on different sides, maximized.
Generated by scripts/build_new_tasks.py from the family "maxcut" of suite/_lib/arnew. Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from arnew import common  # noqa: E402
from arnew import maxcut  # noqa: E402

runtime = common.runtime
DIRECTION = "maximize"
TIMEOUT = 600
P = {'instance': 'G13', 'best_known': None}


def task(module):
    n, edges = maxcut.instance(P["instance"])
    sides = module.solve(n, edges.copy())
    value, details = maxcut.cut_value(sides, n, edges)
    best = P["best_known"]
    return runtime.success(value, "maximize", instance=P["instance"], best_known=best,
                           beats_best_known=None if best is None else value > best, **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
